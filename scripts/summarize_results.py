"""Consolidate every result file into one report-ready summary.

Reads whatever is present in results/ and models/ — single-model metrics,
evaluations, ensembles, error analyses, calibration — and prints a set of
tables plus writes results/SUMMARY.md. Re-runnable at any time; it simply
reflects what has finished so far.

    python scripts/summarize_results.py
"""
from __future__ import annotations

import json
from pathlib import Path

SYSTEM = Path(__file__).resolve().parents[1]
RESULTS = SYSTEM / "results"
MODELS = SYSTEM / "models"


def load(p: Path) -> dict:
    try:
        return json.loads(p.read_text())
    except Exception:
        return {}


def fmt(x, nd=4):
    return f"{x:.{nd}f}" if isinstance(x, (int, float)) else "  -   "


#: Result files from Agents 2 and 3 share the metrics_*.json naming; this summary
#: is Agent 1's, so they are left out.
OTHER_AGENTS = ("field-", "methodology-")


def single_model_rows() -> list[dict]:
    rows = []
    for f in sorted(RESULTS.glob("metrics_*.json")):
        d = load(f)
        if not d or f.stem.replace("metrics_", "").startswith(OTHER_AGENTS):
            continue
        rows.append({
            "model": d.get("tag", f.stem.replace("metrics_", "")),
            "corpus": d.get("corpus", "abstract"),
            "val_f1": d.get("val", {}).get("macro_f1"),
            "test_f1": d.get("test", {}).get("macro_f1"),
            "test_acc": d.get("test", {}).get("accuracy"),
            "train_min": round(d.get("train_seconds", 0) / 60, 1) or None,
        })
    rows.sort(key=lambda r: (r["test_f1"] or 0), reverse=True)
    return rows


def eval_rows() -> list[dict]:
    rows = []
    for f in sorted(RESULTS.glob("eval_*.json")):
        if "documents" in f.name:
            continue
        d = load(f)
        for split, r in d.get("splits", {}).items():
            rows.append({
                "model": d.get("tag", ""), "split": split, "n": r.get("n"),
                "strict_f1": r.get("strict_macro_f1"),
                "co_listed": r.get("co_listed_accuracy"),
                "ece": r.get("ece"),
                "docs_s": r.get("latency", {}).get("docs_per_second"),
            })
    return rows


def ensemble_rows() -> list[dict]:
    rows = []
    for f in sorted(RESULTS.glob("ensemble_*.json")):
        d = load(f)
        if not d or not all(isinstance(m, str) for m in d.get("members", [])):
            continue
        rows.append({
            "ensemble": " + ".join(d.get("members", [])),
            "weights": " / ".join(f"{v:.2f}" for v in d.get("weights", {}).values()),
            "test_f1": d.get("test", {}).get("macro_f1"),
            "test_ece": d.get("test", {}).get("ece"),
            "lift": d.get("test", {}).get("lift_over_best_single"),
        })
    rows.sort(key=lambda r: (r["test_f1"] or 0), reverse=True)
    return rows


def md_table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def main() -> None:
    lines: list[str] = ["# Agent 1 — Results Summary\n",
                        "_Auto-generated by `scripts/summarize_results.py`._\n"]

    print("=" * 70)
    print("SINGLE MODELS (sorted by test macro-F1)")
    print("=" * 70)
    sm = single_model_rows()
    if sm:
        print(f"  {'model':20s} {'corpus':9s} {'val F1':>8s} {'test F1':>8s} "
              f"{'test acc':>9s} {'min':>6s}")
        for r in sm:
            print(f"  {r['model']:20s} {r['corpus']:9s} {fmt(r['val_f1']):>8s} "
                  f"{fmt(r['test_f1']):>8s} {fmt(r['test_acc']):>9s} "
                  f"{fmt(r['train_min'],1):>6s}")
    lines.append("## Single models\n")
    lines.append(md_table(
        ["model", "corpus", "val F1", "test F1", "test acc", "train min"],
        [[r["model"], r["corpus"], fmt(r["val_f1"]), fmt(r["test_f1"]),
          fmt(r["test_acc"]), fmt(r["train_min"], 1)] for r in sm]))

    print("\n" + "=" * 70)
    print("EVALUATION (strict / co-listed / temporal)")
    print("=" * 70)
    ev = eval_rows()
    if ev:
        print(f"  {'model':16s} {'split':14s} {'strict':>8s} {'co-list':>8s} "
              f"{'ECE':>7s} {'docs/s':>7s}")
        for r in ev:
            print(f"  {r['model']:16s} {r['split']:14s} {fmt(r['strict_f1']):>8s} "
                  f"{fmt(r['co_listed']):>8s} {fmt(r['ece']):>7s} "
                  f"{fmt(r['docs_s'],1):>7s}")
    lines.append("\n## Evaluation\n")
    lines.append(md_table(
        ["model", "split", "strict F1", "co-listed", "ECE", "docs/s"],
        [[r["model"], r["split"], fmt(r["strict_f1"]), fmt(r["co_listed"]),
          fmt(r["ece"]), fmt(r["docs_s"], 1)] for r in ev]))

    print("\n" + "=" * 70)
    print("ENSEMBLES (sorted by test macro-F1)")
    print("=" * 70)
    en = ensemble_rows()
    if en:
        for r in en:
            print(f"  {r['ensemble']:40s} F1={fmt(r['test_f1'])} "
                  f"ECE={fmt(r['test_ece'])} lift={fmt(r['lift'])}")
    lines.append("\n## Ensembles\n")
    lines.append(md_table(
        ["ensemble", "weights", "test F1", "test ECE", "lift vs best single"],
        [[r["ensemble"], r["weights"], fmt(r["test_f1"]), fmt(r["test_ece"]),
          fmt(r["lift"])] for r in en]))

    # Error analysis, if present.
    ea = sorted(RESULTS.glob("error_analysis_*_test.json"))
    if ea:
        d = load(ea[-1])
        lines.append("\n## Error decomposition (best available)\n")
        dec = d.get("decomposition", {})
        n_err = d.get("n_errors", 1)
        lines.append(
            f"- members: {', '.join(d.get('members', []))}\n"
            f"- strict accuracy: {d.get('strict_accuracy')}\n"
            f"- defensible errors (co-listed + adjacent): "
            f"{(dec.get('co_listed',0)+dec.get('adjacent',0))/max(1,n_err):.1%} "
            f"of errors\n"
            f"- genuine confusion: {dec.get('genuine',0)/max(1,n_err):.1%} "
            f"of errors\n"
            f"- accuracy crediting defensible: "
            f"{d.get('defensible_credited_accuracy')}\n")
        print("\n" + "=" * 70)
        print(f"ERROR DECOMPOSITION ({', '.join(d.get('members', []))})")
        print("=" * 70)
        print(f"  strict acc {d.get('strict_accuracy')}  |  "
              f"defensible-credited {d.get('defensible_credited_accuracy')}")

    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nwrote {RESULTS / 'SUMMARY.md'}")


if __name__ == "__main__":
    main()
